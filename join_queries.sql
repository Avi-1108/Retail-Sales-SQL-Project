-- Q17. Create a SELF JOIN challenge.
SELECT c1.customer_name,c2.customer_name,c2.city FROM customers c1
LEFT JOIN customers c2
ON c1.city=c2.city
WHERE c1.customer_id != c2.customer_id;

-- Q18. Simulate a FULL OUTER JOIN in MySQL.
