INNER JOIN orders
ON customers.customer_id=orders.customer_id;

-- Q2. Display: Customer Name + Order Date + Status
SELECT customer_name,order_date,order_status FROM customers
INNER JOIN orders
ON customers.customer_id=orders.customer_id;

